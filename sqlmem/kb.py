"""KnowledgeBase: one folder holding catalog, curated semantics, memories, generated docs and the search index.

<kb>/catalog.json          raw facts scanned from the database (re-generated by `scan`)
<kb>/semantic.yaml         curated business meaning (human/LLM edited, never overwritten)
<kb>/knowledge_graph.yaml  business entities + relations (generated by `sqlmem graph`, editable)
<kb>/memories.jsonl        learned memories (appended by `remember`)
<kb>/sqlmem.json           settings: embedder, LLM (no secrets)
<kb>/docs/                 generated Markdown knowledge cards, ER diagrams, knowledge graph views
<kb>/graph.json            full graph (tables, domains, metrics, terms, entities + edges)
<kb>/index.db              derived hybrid search index (safe to delete; rebuilt by `build`)
"""

